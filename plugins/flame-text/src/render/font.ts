/** How many dots wide a letter is, and the gap after it. */
export const GLYPH_WIDTH = 5
export const ADVANCE = 6.5
/** The width of a space. */
export const SPACE = 4
/** The height of a line of dots, with room for tails, and the gap between lines. */
export const LINE_ROWS = 9
export const LINE_GAP = 3

/**
 * Turns a message into text the font can draw: accents are dropped (é becomes e), curly quotes become straight and tabs
 * become spaces.
 *
 * @returns The text, or nothing when it has a character that cannot be drawn (an emoji or another alphabet).
 */
export function drawable(text: string): string | undefined {
	let out = ''
	for (const original of text.normalize('NFD')) {
		if (/[̀-ͯ\r]/.test(original)) continue
		const char = original === '\t' ? ' ' : original
		const like = LOOKALIKES[char]
		const use = like ?? char
		for (const piece of use) {
			if (piece !== '\n' && !(piece in GLYPHS)) return undefined
			out += piece
		}
	}
	return out
}

/** The width of one character in dots, with the gap. */
export const widthOf = (char: string): number =>
	char === ' ' ? SPACE : ADVANCE

/** The dots of one character as `[column, row]` pairs. */
export function dotsOf(char: string): Array<[number, number]> {
	const glyph = GLYPHS[char]
	if (!glyph || glyph[1] === '') return []
	const dots: Array<[number, number]> = []
	glyph[1].split('/').forEach((line, index) => {
		for (let column = 0; column < line.length; column++)
			if (line[column] === '#') dots.push([column, glyph[0] + index])
	})
	return dots
}

/** Every character the font has. For tests. */
export const FONT_CHARACTERS = Object.keys(GLYPHS)

/** One character as lines of `#` and `.`, for looking at it. For tests. */
export function picture(char: string): string[] {
	const rows: string[] = []
	for (let row = 0; row < LINE_ROWS; row++) rows.push('.'.repeat(GLYPH_WIDTH))
	for (const [column, row] of dotsOf(char)) {
		const line = rows[row]
		if (line === undefined) continue
		rows[row] = `${line.slice(0, column)}#${line.slice(column + 1)}`
	}
	return rows
}
